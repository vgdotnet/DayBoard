"""Generates app/src/main/java/io/github/vgdotnet/dayboard/mining/Sha256Kernel.kt.

The kernel is the ESP32 miner's sha.cpp ported to Kotlin: everything that does not depend on the
nonce is computed once per job (midstate, rounds 0-2 of the second header block, the constant parts
of the message schedule), the schedule of the second block is shared by all version-rolling
variants, and the second hash stops after round 60 because only H7 is needed to test the top 16
bits of the hash. Rounds are fully unrolled here instead of the RND8 macros of the C source.
"""
